import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

import { pluginManifest, PLUGIN_KEY, startFakeGenerationPlugin } from "../testing/fake-generation-plugin-server.ts";
import { generationHarness, type GenerationHarness } from "../testing/project-generation-harness.ts";
import { buildZip } from "../testing/zip-fixture.ts";

let harness: GenerationHarness | undefined;
const fakes: Array<{ close(): Promise<void> }> = [];
afterEach(async () => {
  await harness?.close();
  harness = undefined;
  for (const fake of fakes.splice(0)) await fake.close();
});

const install = (h: GenerationHarness, manifest: unknown) => h.plugins.install("acme.zip", buildZip([{ name: "plugin.json", data: JSON.stringify(manifest) }]));

async function withPlugin() {
  const image = await startFakeGenerationPlugin();
  fakes.push(image);
  harness = await generationHarness();
  const h = harness;
  const folder = h.project("film");
  const plugin = install(h, pluginManifest(image.url));
  expect(plugin.configured).toBe(false);
  h.plugins.save("acme-images", { values: { apiKey: PLUGIN_KEY } });
  const saved = await h.api.saveSettings("film", {
    image: { plugin: "acme-images", server: null, defaults: { model: "pixel-1", aspect: "16:9", quality: "hd", count: 2 } },
  } as never);
  expect(saved).toHaveProperty("settings");
  return { h, folder, image };
}

describe("a project generated by an installed plugin", () => {
  it("lists the plugin's models for the project and makes the pictures through its requests", async () => {
    const { h, folder, image } = await withPlugin();
    const listed = await h.api.models("film", "image");
    expect("models" in listed && listed.models.map((model) => model.id)).toEqual(["pixel-1"]);

    const started = await h.api.start("film", { kind: "image", nodeId: "node-1", prompt: "a lighthouse at dusk", name: "镜头 1" }, { requester: { kind: "person" } });
    if (!("job" in started)) throw new Error(JSON.stringify(started));
    expect(started.job).toMatchObject({ plugin: "acme-images", server: "acme-images", tool: "generate_image" });
    const done = await h.ended("film", started.job.id);

    expect(done.status, JSON.stringify(done.failure)).toBe("done");
    expect(done.files).toHaveLength(1);
    expect(existsSync(join(folder, ...done.files[0]!.path.split("/")))).toBe(true);
    const call = image.calls.find((entry) => entry.path === "/v1/images")!;
    expect(call.body).toMatchObject({ model: "pixel-1", prompt: "a lighthouse at dusk", n: 2, aspect_ratio: "16:9", quality: "hd" });
    expect(done.progress).toBe(1);
  });

  it("asks again for the models at once after the plugin's file changes, and uses a new address after its settings change", async () => {
    const { h } = await withPlugin();
    const next = pluginManifest("http://127.0.0.1:9/");
    next.models = [
      { id: "pixel-2", name: "Pixel 2", kind: "image", aspects: ["1:1"], qualities: ["auto"], maxCount: 1, referenceImages: false },
    ] as never;
    install(h, next);
    const listed = await h.api.models("film", "image");
    expect("models" in listed && listed.models.map((model) => model.id)).toEqual(["pixel-2"]);
    install(h, pluginManifest(await (async () => {
      const other = await startFakeGenerationPlugin({ mode: "files" });
      fakes.push(other);
      return other.url;
    })()));
    h.plugins.save("acme-images", { values: { apiKey: PLUGIN_KEY } });
    const changed = await h.api.models("film", "image");
    expect("models" in changed && changed.models.map((model) => model.id)).toEqual(["pixel-1"]);
  });

  it("keeps an old project on its MCP server when it has no plugin", async () => {
    const h = await generationHarness();
    harness = h;
    h.project("film");
    const saved = await h.api.saveSettings("film", { image: { server: "gen", defaults: { model: "pixel-1", aspect: "1:1", quality: "standard", count: 1 } } } as never);
    expect(saved).toHaveProperty("settings");
    expect((saved as { settings: { image: { plugin?: string | null; server: string } } }).settings.image.plugin ?? null).toBeNull();
    const started = await h.api.start("film", { kind: "image", nodeId: "node-1", prompt: "legacy" }, { requester: { kind: "person" } });
    if (!("job" in started)) throw new Error(JSON.stringify(started));
    expect(started.job.plugin).toBeUndefined();
    expect((await h.ended("film", started.job.id)).status).toBe("done");
  });

  it("never writes the key into a job, a log line or a saved file", async () => {
    const { h, folder } = await withPlugin();
    const started = await h.api.start("film", { kind: "image", nodeId: "node-1", prompt: "a [refuse] prompt" }, { requester: { kind: "person" } });
    if (!("job" in started)) throw new Error(JSON.stringify(started));
    const failed = await h.ended("film", started.job.id);
    expect(failed.status).toBe("failed");
    expect(failed.failure?.reason).not.toContain(PLUGIN_KEY);
    const everything = JSON.stringify([failed, h.logs, h.api.jobs("film")]);
    expect(everything).not.toContain(PLUGIN_KEY);
    void folder;
    void readFileSync;
  });
});
